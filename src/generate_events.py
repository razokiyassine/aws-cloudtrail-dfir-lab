def iso(t: datetime) -> str:
    """Format de date CloudTrail : 2026-10-29T02:14:30Z"""
    return t.strftime("%Y-%m-%dT%H:%M:%SZ")


class Gen:
    """Fabrique d'enregistrements au format CloudTrail + registre du corrigé."""

    def __init__(self, seed: int):
        self.rng = random.Random(seed)
        self.key: dict[str, dict] = {}   # corrigé : eventID -> infos

    # ---------- utilitaires ----------
    def uid(self) -> str:
        return str(uuid.UUID(int=self.rng.getrandbits(128), version=4))

    def hexstr(self, n: int) -> str:
        return "".join(self.rng.choice("0123456789ABCDEF") for _ in range(n))

    def tag(self, rec: dict, scenario: str, role: str, note: str = "") -> dict:
        """Enregistre l'événement dans le corrigé (jamais dans l'événement lui-même)."""
        self.key[rec["eventID"]] = {
            "scenario": scenario, "role": role, "eventName": rec["eventName"],
            "eventTime": rec["eventTime"], "note": note,
        }
        return rec

    # ---------- identités ----------
    def iam_user(self, user: str, *, key: str | None = None, console_at: datetime | None = None,
                 mfa: bool = True) -> dict:
        u = USERS[user]
        ident = {
            "type": "IAMUser",
            "principalId": ("AIDALAB" + user.upper().replace("-", "")).ljust(21, "0")[:21],
            "arn": f"arn:aws:iam::{ACCOUNT}:user/{user}",
            "accountId": ACCOUNT,
            "accessKeyId": key or u["key"],
            "userName": user,
        }
        if console_at is not None:       # appel API réalisé depuis une session console
            ident["accessKeyId"] = "ASIALAB" + self.hexstr(13)
            ident["sessionContext"] = {"attributes": {
                "creationDate": iso(console_at),
                "mfaAuthenticated": "true" if mfa else "false"}}
        return ident

    def monitor_role(self) -> dict:
        return {
            "type": "AssumedRole",
            "principalId": "AROALABMONITOR00001:monitor",
            "arn": f"arn:aws:sts::{ACCOUNT}:assumed-role/MonitoringRole/monitor",
            "accountId": ACCOUNT,
            "accessKeyId": "ASIALABMONITOR00001",
            "sessionContext": {
                "sessionIssuer": {"type": "Role", "principalId": "AROALABMONITOR00001",
                                  "arn": f"arn:aws:iam::{ACCOUNT}:role/MonitoringRole",
                                  "accountId": ACCOUNT, "userName": "MonitoringRole"},
                "attributes": {"mfaAuthenticated": "false", "creationDate": "2026-10-28T05:50:00Z"}},
        }

    # ---------- enregistrement générique ----------
    def rec(self, t: datetime, source: str, name: str, ident: dict, ip: str, *,
            region: str = HOME_REGION, params=None, resp=None, ua: str = UA_CLI,
            error: str | None = None, msg: str | None = None, ro: bool = False,
            etype: str = "AwsApiCall", category: str = "Management",
            extra: dict | None = None, resources: list | None = None) -> dict:
        r: dict = {
            "eventVersion": "1.09",
            "userIdentity": ident,
            "eventTime": iso(t),
            "eventSource": source,
            "eventName": name,
            "awsRegion": region,
            "sourceIPAddress": ip,
            "userAgent": ua,
        }
        if error:
            r["errorCode"] = error
            r["errorMessage"] = msg or "Access denied"
        r["requestParameters"] = params
        r["responseElements"] = None if error else resp
        if extra:
            r["additionalEventData"] = extra
        r["requestID"] = self.uid()
        r["eventID"] = self.uid()
        r["readOnly"] = ro
        if resources:
            r["resources"] = resources
        r["eventType"] = etype
        r["managementEvent"] = category == "Management"
        r["recipientAccountId"] = ACCOUNT
        r["eventCategory"] = category
        if etype == "AwsApiCall":
            r["tlsDetails"] = {"tlsVersion": "TLSv1.3", "cipherSuite": "TLS_AES_128_GCM_SHA256",
                               "clientProvidedHostHeader": source.replace(".amazonaws.com", f".{region}.amazonaws.com")}
        return r

    def console_login(self, t, user, ip, ua, *, ok=True, mfa=True) -> dict:
        ident = self.iam_user(user)
        ident.pop("accessKeyId")        # pas de clé d'accès pour une connexion console
        r = self.rec(
            t, "signin.amazonaws.com", "ConsoleLogin", ident, ip, region=GLOBAL_REGION, ua=ua,
            params=None, resp={"ConsoleLogin": "Success" if ok else "Failure"},
            error=None, etype="AwsConsoleSignIn",
            extra={"LoginTo": "https://console.aws.amazon.com/console/home?state=hashArgs%23&isauthcode=true",
                   "MobileVersion": "No", "MFAUsed": "Yes" if mfa else "No"})
        if not ok:
            r["errorMessage"] = "Failed authentication"
        r.pop("tlsDetails", None)
        return r


