def s3_data_event(g: Gen, t, user, op, bucket, objkey):
    ident = g.iam_user(user)
    return g.rec(
        t, "s3.amazonaws.com", op, ident, USERS[user]["ip"], ua=UA_CLI, ro=(op == "GetObject"),
        category="Data",
        params={"bucketName": bucket, "Host": f"{bucket}.s3.{HOME_REGION}.amazonaws.com", "key": objkey},
        extra={"SignatureVersion": "SigV4", "CipherSuite": "TLS_AES_128_GCM_SHA256",
               "AuthenticationMethod": "AuthHeader", "bytesTransferredIn": 0 if op == "GetObject" else 2048,
               "bytesTransferredOut": 2048 if op == "GetObject" else 0},
        resources=[{"type": "AWS::S3::Object", "ARN": f"arn:aws:s3:::{bucket}/{objkey}"},
                   {"accountId": ACCOUNT, "type": "AWS::S3::Bucket", "ARN": f"arn:aws:s3:::{bucket}"}])


