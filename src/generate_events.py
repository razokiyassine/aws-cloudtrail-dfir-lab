def write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def wrap(records: list[dict]) -> dict:
    return {"_lab_notice": LAB_NOTICE, "Records": records}


def write_s3_layout(g: Gen, records: list[dict], root: Path) -> int:
    """Regroupe par (région, créneau de 15 min) et écrit des .json.gz comme CloudTrail->S3."""
    groups: dict[tuple, list[dict]] = {}
    for r in records:
        t = datetime.strptime(r["eventTime"], "%Y-%m-%dT%H:%M:%SZ")
        slot = t.replace(minute=(t.minute // 15) * 15, second=0)
        groups.setdefault((r["awsRegion"], slot), []).append(r)
    for (region, slot), recs in sorted(groups.items()):
        rnd = g.hexstr(10).lower()
        fname = f"{ACCOUNT}_CloudTrail_{region}_{slot.strftime('%Y%m%dT%H%MZ')}_{rnd}.json.gz"
        out = (root / "AWSLogs" / ACCOUNT / "CloudTrail" / region / slot.strftime("%Y") /
               slot.strftime("%m") / slot.strftime("%d") / fname)
        out.parent.mkdir(parents=True, exist_ok=True)
        with gzip.open(out, "wt", encoding="utf-8") as fh:
            json.dump(wrap(recs), fh, ensure_ascii=False, separators=(",", ":"))
    return len(groups)


SCENARIO_FILES = {
    "S1": "S1_cle_acces_non_autorisee.json",
    "S2": "S2_administrator_access.json",
    "S3": "S3_suppression_bucket.json",
    "S4": "S4_arret_journalisation.json",
    "S5": "S5_connexion_sans_mfa.json",
    "S6": "S6_acces_refuse.json",
}


def generate(seed: int = 42, out: str = "data", teacher_dir: str = "teacher", quiet: bool = False) -> dict:
    g = Gen(seed)
    normal = build_normal(g)
    attack, gap = build_attack(g)

    # Réalisme : une fois StopLogging exécuté, CloudTrail ne journalise plus RIEN
    # jusqu'à StartLogging. On retire donc les événements "normaux" de cette fenêtre.
    stop = datetime.strptime(gap["stop"], "%Y-%m-%dT%H:%M:%SZ")
    start = datetime.strptime(gap["start"], "%Y-%m-%dT%H:%M:%SZ")
    inside = lambda r: stop < datetime.strptime(r["eventTime"], "%Y-%m-%dT%H:%M:%SZ") < start
    normal = [r for r in normal if not inside(r)]

    normal.sort(key=lambda r: r["eventTime"])
    attack.sort(key=lambda r: r["eventTime"])
    full = sorted(normal + attack, key=lambda r: r["eventTime"])

    out_p = Path(out)
    write_json(out_p / "dataset_normal.json", wrap(normal))
    write_json(out_p / "dataset_attack.json", wrap(attack))
    write_json(out_p / "dataset_full.json", wrap(full))
    for sc, fname in SCENARIO_FILES.items():
        recs = [r for r in attack if g.key.get(r["eventID"], {}).get("scenario") == sc]
        write_json(out_p / "scenarios" / fname, wrap(recs))
    n_files = write_s3_layout(g, full, out_p / "s3_layout")

    key = {"_notice": "CORRIGÉ ENSEIGNANT - ne pas distribuer aux étudiants.",
           "seed": seed, "logging_gap": gap,
           "events": {eid: g.key[eid] for eid in sorted(g.key, key=lambda e: g.key[e]["eventTime"])}}
    write_json(Path(teacher_dir) / "answer_key.json", key)

    stats = {"normal": len(normal), "attack": len(attack), "total": len(full), "s3_files": n_files,
             "gap": gap}
    if not quiet:
        print(f"[OK] Événements SYNTHÉTIQUES générés (seed={seed})")
        print(f"     normaux/leurres : {len(normal)} | attaque+réponse : {len(attack)} | total : {len(full)}")
        print(f"     fichiers .json.gz (disposition S3) : {n_files} -> {out_p/'s3_layout'}")
        print(f"     fenêtre sans journal : StopLogging {gap['stop']} -> StartLogging {gap['start']}")
        print(f"     corrigé enseignant : {Path(teacher_dir)/'answer_key.json'}")
    return stats


def main() -> None:
    ap = argparse.ArgumentParser(description="Génère des événements SYNTHÉTIQUES au format CloudTrail.")
    ap.add_argument("--seed", type=int, default=42, help="graine aléatoire (défaut 42)")
    ap.add_argument("--out", default="data", help="dossier de sortie des jeux de données")
    ap.add_argument("--teacher-dir", default="teacher", help="dossier du corrigé enseignant")
    a = ap.parse_args()
    generate(a.seed, a.out, a.teacher_dir)


if __name__ == "__main__":
    main()
